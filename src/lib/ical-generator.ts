/**
 * RFC 5545 compliant iCalendar (.ics) generator.
 * Produces structured focus events for Google Calendar, Apple Calendar, and Microsoft Outlook.
 *
 * Implements empathetic, cognitive-friendly scheduling:
 * - Allocates realistic focus blocks based on task effort estimates (15-45 mins).
 * - Leaves 10-minute cognitive transition buffers between steps.
 * - Caps daily work blocks to normal daytime hours (9:00 AM - 5:00 PM), rolling excess to the next business day.
 */

export interface ICalTask {
  id: string;
  title: string;
  description: string;
  status: string;
  effortMin?: number | null;
  effortMax?: number | null;
  rationale?: string | null;
  note?: string | null;
  sortOrder?: number;
}

export interface ICalPlan {
  id: string;
  title: string;
  desiredOutcome?: string | null;
  horizonDate?: string | null;
  tasks: ICalTask[];
}

export interface ICalGeneratorOptions {
  startDate?: Date;
  includeCompleted?: boolean;
}

export function formatICalDate(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, "0");
  return (
    d.getUTCFullYear() +
    pad(d.getUTCMonth() + 1) +
    pad(d.getUTCDate()) +
    "T" +
    pad(d.getUTCHours()) +
    pad(d.getUTCMinutes()) +
    pad(d.getUTCSeconds()) +
    "Z"
  );
}

export function escapeICalText(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\r?\n/g, "\\n");
}

export function foldICalLine(line: string): string {
  if (line.length <= 75) return line;
  const parts: string[] = [];
  let remaining = line;
  while (remaining.length > 75) {
    parts.push(remaining.slice(0, 75));
    remaining = " " + remaining.slice(75);
  }
  parts.push(remaining);
  return parts.join("\r\n");
}

export function generatePlanICalendar(
  plan: ICalPlan,
  options: ICalGeneratorOptions = {},
): string {
  const now = new Date();
  const dtStamp = formatICalDate(now);

  // Filter tasks based on options (default: only open/actionable tasks)
  const tasksToSchedule = (
    options.includeCompleted
      ? plan.tasks
      : plan.tasks.filter((t) => t.status !== "done")
  ).sort((a, b) => (a.sortOrder ?? 0) - (b.sortOrder ?? 0));

  // Determine starting point (default: tomorrow at 9:00 AM UTC)
  const cursor = options.startDate
    ? new Date(options.startDate.getTime())
    : new Date(now.getTime() + 24 * 60 * 60 * 1000);

  cursor.setUTCHours(9, 0, 0, 0);

  const lines: string[] = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//ClearStep//Executive Function Planner//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    `X-WR-CALNAME:${escapeICalText(plan.title)} - Clearstep`,
    "X-WR-TIMEZONE:UTC",
  ];

  tasksToSchedule.forEach((task, index) => {
    // Estimate focus duration (default 25m, clamped between 15m and 60m)
    const rawEffort = task.effortMin ?? 25;
    const durationMinutes = Math.max(15, Math.min(60, rawEffort));

    // If current cursor hour is past 5:00 PM (17:00), roll to tomorrow 9:00 AM
    if (cursor.getUTCHours() >= 17) {
      cursor.setUTCDate(cursor.getUTCDate() + 1);
      cursor.setUTCHours(9, 0, 0, 0);
    }

    const start = new Date(cursor.getTime());
    const end = new Date(start.getTime() + durationMinutes * 60 * 1000);

    // Build event description
    const descParts: string[] = [];
    if (task.description) {
      descParts.push(task.description);
    }
    if (task.rationale) {
      descParts.push(`Why: ${task.rationale}`);
    }
    if (task.note) {
      descParts.push(`Note: ${task.note}`);
    }
    if (plan.desiredOutcome) {
      descParts.push(`Target Outcome: ${plan.desiredOutcome}`);
    }
    descParts.push("Generated by Clearstep — https://github.com/SakshamJ01/clearstep");

    const description = descParts.join("\n\n");
    const uid = `task-${task.id || index}-${now.getTime()}@clearstep.app`;

    lines.push("BEGIN:VEVENT");
    lines.push(`UID:${uid}`);
    lines.push(`DTSTAMP:${dtStamp}`);
    lines.push(`DTSTART:${formatICalDate(start)}`);
    lines.push(`DTEND:${formatICalDate(end)}`);
    lines.push(`SUMMARY:${escapeICalText(`${index + 1}. ${task.title}`)}`);
    lines.push(`DESCRIPTION:${escapeICalText(description)}`);
    lines.push("STATUS:CONFIRMED");
    lines.push("TRANSP:OPAQUE");
    lines.push("SEQUENCE:0");
    lines.push("END:VEVENT");

    // Advance cursor by duration + 10-minute transition buffer
    cursor.setTime(end.getTime() + 10 * 60 * 1000);
  });

  lines.push("END:VCALENDAR");

  // Format with standard CRLF and line-folding
  return lines.map(foldICalLine).join("\r\n") + "\r\n";
}
